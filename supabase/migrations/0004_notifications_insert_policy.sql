-- =============================================================
-- BOOK STEP: notifications への insert を許可するポリシーを追加
-- -------------------------------------------------------------
-- 背景: 当初は「通知の作成はservice role/トリガー経由のみ」を想定してINSERTポリシーを
-- 意図的に設定していなかったが、実装(sendFriendRequest等のServer Action)は
-- 通常のRLS適用クライアントからinsertしていたため、常にRLSで拒否され、
-- 友達申請などの通知が一切作成されない不具合が発生していた。
--
-- 対応: 自分自身をactor_idとして記録する通知のみ作成を許可する
-- (「なりすまし」で他人が行った行動であるかのような通知を作れないようにするための制限)
-- =============================================================

create policy "notifications_insert_as_actor" on notifications
  for insert with check (actor_id = auth.uid());
